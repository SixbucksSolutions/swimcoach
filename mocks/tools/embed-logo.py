#!/usr/bin/env python3
"""Embed the swimcoach mark into an HTML page: favicon, header mark, and home-screen icon.

    python mocks/tools/embed-logo.py                            (mocks/index.html)
    python mocks/tools/embed-logo.py --target public/index.html

Run it on both pages: the mock is the approved reference and public/index.html is the MVP page.

design/logo/swimcoach.svg is the ONE definition of the mark. This writes it, between the LOGO:BEGIN
and LOGO:END markers, as:
    <link rel="icon">              the SVG as a data URI, for the browser tab
    <link rel="apple-touch-icon">  design/logo/swimcoach-touch-180.png, for iPhone "Add to Home Screen",
                                   which ignores SVG icons. Embedded as a data URI in the mock; the
                                   public/ page links /icons/touch-180.png instead (one source)
    --brand                        the same SVG data URI as a CSS variable, drawn by #brand in the header
Re-run render-logo.py first if the SVG changed, so the PNG matches.
"""

import argparse
import base64
import re
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "design" / "logo" / "swimcoach.svg"
TOUCH = ROOT / "design" / "logo" / "swimcoach-touch-180.png"
PAGE = ROOT / "mocks" / "index.html"
MARKERS = re.compile(r"(<!--LOGO:BEGIN-->).*?(<!--LOGO:END-->)", re.DOTALL)


def svg_data_uri(svg: str) -> str:
    """Minify and percent-encode the SVG. Every '#' MUST be escaped, or the URI ends at the first color."""
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.DOTALL)
    svg = re.sub(r">\s+<", "><", svg).strip()
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe="")


def block(svg_uri: str, touch_href: str) -> str:
    """The head markup written between the markers."""
    return (
        "\n<!-- swimcoach mark, generated by mocks/tools/embed-logo.py from design/logo/. Do not edit here. -->\n"
        f'<link rel="icon" type="image/svg+xml" href="{svg_uri}">\n'
        f'<link rel="apple-touch-icon" href="{touch_href}">\n'
        f"<style>:root{{--brand:url(\"{svg_uri}\")}}</style>\n"
    )


def shown(path: Path) -> str:
    """The path relative to the repository when it is inside it, for the closing message."""
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)


def main() -> None:
    parser = argparse.ArgumentParser(description="Embed the swimcoach mark into an HTML page.")
    parser.add_argument(
        "--target",
        type=Path,
        default=PAGE,
        help="the HTML file to write into (default: mocks/index.html)",
    )
    page: Path = parser.parse_args().target.resolve()
    # newline="" on both ends: read_text() would turn CRLF into LF and the write would keep it.
    with page.open(encoding="utf-8", newline="") as f:
        html = f.read()
    if not MARKERS.search(html):
        raise SystemExit(f"LOGO:BEGIN / LOGO:END markers not found in {page}")
    uri = svg_data_uri(SVG.read_text(encoding="utf-8"))
    if page.is_relative_to(ROOT / "public"):
        # The MVP page links the icon the Worker serves, so the home-screen icon has one source.
        touch_href = "/icons/touch-180.png"
    else:
        touch_href = "data:image/png;base64," + base64.b64encode(TOUCH.read_bytes()).decode("ascii")
    html = MARKERS.sub(lambda m: m.group(1) + block(uri, touch_href) + m.group(2), html, count=1)
    with page.open("w", encoding="utf-8", newline="") as f:
        f.write(html)
    print(f"Embedded {SVG.name} ({len(uri):,} chars as a URI) and {TOUCH.name} into {shown(page)}")


if __name__ == "__main__":
    main()
